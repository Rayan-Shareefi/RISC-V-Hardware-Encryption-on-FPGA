"""
gen_poly1305_vectors.py  -  make the Poly1305 test vectors for the RISC-V programs

1) Reads the official test vectors from RFC 8439 (scripts/rfc8439.txt):
   section 2.5.2 and Appendix A.3 (#1 .. #11, incl. the tricky edge cases).
2) Checks them with an independent reference: Poly1305 written directly from
   the RFC formula with Python big integers (no 26-bit limbs, no tricks).
3) Uses the reference to make tags for every message length 0..64 bytes
   (tests the partial-block padding).
4) Writes poly1305_vectors.h for the C programs.
5) Writes hw/tb_poly1305_vectors_pkg.vhd for the hardware testbench, incl. long
   messages (> 64 bytes, sent to the hardware in pieces): RFC A.3 #2-#4 and the
   MAC input of the ChaCha20-Poly1305 AEAD example RFC 8439 2.8.2 (made here
   with a Python ChaCha20 written from the RFC and checked against its tag).

Run:  python scripts/gen_poly1305_vectors.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RFC = (ROOT / "scripts" / "rfc8439.txt").read_text()
OUT = ROOT / "neorv32-main" / "sw" / "example" / "demo_blink_led" / "poly1305_vectors.h"


def poly1305_ref(key: bytes, msg: bytes) -> bytes:
    """RFC 8439 2.5.1, straight from the formula."""
    r = int.from_bytes(key[:16], "little") & 0x0FFFFFFC0FFFFFFC0FFFFFFC0FFFFFFF
    s = int.from_bytes(key[16:32], "little")
    p = (1 << 130) - 5
    acc = 0
    for i in range(0, len(msg), 16):
        n = int.from_bytes(msg[i:i + 16] + b"\x01", "little")
        acc = (acc + n) * r % p
    return ((acc + s) % (1 << 128)).to_bytes(16, "little")


# ---- read the RFC ---------------------------------------------------------
lines = [l for l in RFC.splitlines()
         if not l.startswith("Nir & Langley") and not l.startswith("RFC 8439 ") and "\f" not in l]

DUMP = re.compile(r"^\s*\d{3}  ((?:[0-9a-fA-F]{2} ){0,15}[0-9a-fA-F]{2})")   # "000  43 72 ..."
ROW = re.compile(r"^\s+((?:[0-9a-fA-F]{2} ?){1,16})\s*$")                      # "   02 00 00 ..."


def read_bytes(start, pattern):
    """bytes from consecutive matching lines after line index start"""
    out, i = b"", start
    while i < len(lines) and (not lines[i].strip() or pattern.match(lines[i])):
        m = pattern.match(lines[i])
        if m:
            out += bytes.fromhex(m.group(1))
        elif out:
            break
        i += 1
    return out


def find(label, frm):
    for i in range(frm, len(lines)):
        if lines[i].strip().startswith(label):
            return i
    raise ValueError(label)


def heading(text):
    """line index of a section heading (exact line, so the table of contents is skipped)"""
    return next(i for i, l in enumerate(lines) if l.strip() == text)


vectors = []

# 2.5.2: key = r || s, message dump, "Tag: a8:06:..."
i = heading("2.5.2.  Poly1305 Example and Test Vector")
r = bytes.fromhex(lines[find("o  r before clamping:", i)].split(":", 1)[1].replace(":", "").strip())
s = bytes.fromhex(lines[find("o  s as an octet string:", i) + 1].replace(":", "").strip())
msg = read_bytes(find("Message to be Authenticated:", i) + 1, DUMP)
tag = bytes.fromhex(lines[find("Tag:", i)].split(":", 1)[1].replace(":", "").strip())
vectors.append(("RFC 8439 2.5.2", r + s, msg, tag))

# A.3 #1 .. #11
a3 = heading("A.3.  Poly1305 Message Authentication Code")
a4 = heading("A.4.  Poly1305 Key Generation Using ChaCha20")
for n in range(1, 12):
    i = find(f"Test Vector #{n}:", a3)
    assert i < a4
    if n <= 4:
        key = read_bytes(find("One-time Poly1305 Key:", i) + 1, DUMP)
        msg = read_bytes(find("Text to MAC:", i) + 1, DUMP)
        tag = read_bytes(find("Tag:", i) + 1, DUMP)
    else:
        key = read_bytes(find("R:", i) + 1, ROW) + read_bytes(find("S:", i) + 1, ROW)
        msg = read_bytes(find("data:", i) + 1, ROW)
        tag = read_bytes(find("tag:", i) + 1, ROW)
    vectors.append((f"RFC 8439 A.3 #{n}", key, msg, tag))

# ---- check the reference against the RFC ---------------------------------
for name, key, msg, tag in vectors:
    assert len(key) == 32 and len(tag) == 16, name
    assert poly1305_ref(key, msg) == tag, f"reference does not match {name}"
print(f"reference matches all {len(vectors)} RFC vectors")

# ---- every length 0..64 (2.5.2 key, fixed 64-byte pattern) ----------------
sweep_key = vectors[0][1]
sweep_msg = bytes((7 * i + 1) & 0xFF for i in range(64))
sweep_tags = [poly1305_ref(sweep_key, sweep_msg[:n]) for n in range(65)]


# ---- write the C header ----------------------------------------------------
def c_bytes(b, indent="  "):
    rows = [", ".join(f"0x{x:02x}" for x in b[k:k + 16]) for k in range(0, len(b), 16)]
    return (",\n" + indent).join(rows) if rows else ""


with OUT.open("w", newline="\n") as f:
    f.write("/* poly1305_vectors.h - generated by scripts/gen_poly1305_vectors.py, do not edit.\n"
            " * Official RFC 8439 test vectors (2.5.2, A.3 #1-#11) and tags for every\n"
            " * message length 0..64 from an independent big-integer reference. */\n")
    f.write("#ifndef POLY1305_VECTORS_H\n#define POLY1305_VECTORS_H\n\n#include <stdint.h>\n\n")
    for k, (name, key, msg, tag) in enumerate(vectors):
        f.write(f"/* {name} */\n")
        f.write(f"static const uint8_t pv{k}_key[32] = {{\n  {c_bytes(key)}\n}};\n")
        f.write(f"static const uint8_t pv{k}_msg[{max(len(msg), 1)}] = {{\n  {c_bytes(msg) or '0'}\n}};\n")
        f.write(f"static const uint8_t pv{k}_tag[16] = {{\n  {c_bytes(tag)}\n}};\n\n")
    f.write("typedef struct { const char *name; const uint8_t *key; const uint8_t *msg; uint32_t len; const uint8_t *tag; } poly_vec_t;\n\n")
    f.write("static const poly_vec_t POLY_VECTORS[] = {\n")
    for k, (name, key, msg, tag) in enumerate(vectors):
        f.write(f"  {{ \"{name}\", pv{k}_key, pv{k}_msg, {len(msg)}, pv{k}_tag }},\n")
    f.write("};\n#define POLY_NUM_VECTORS (sizeof(POLY_VECTORS) / sizeof(POLY_VECTORS[0]))\n\n")
    f.write("/* length sweep: key = RFC 8439 2.5.2 key, message = first n bytes of SWEEP_MSG */\n")
    f.write(f"static const uint8_t SWEEP_MSG[64] = {{\n  {c_bytes(sweep_msg)}\n}};\n")
    f.write("static const uint8_t SWEEP_TAGS[65][16] = {\n")
    f.write(",\n".join("  { " + c_bytes(t) + " }" for t in sweep_tags))
    f.write("\n};\n\n#endif\n")
print(f"wrote {OUT.relative_to(ROOT)}")


# ---- ChaCha20 + ChaCha20-Poly1305 AEAD (RFC 8439 2.3 / 2.6 / 2.8), straight from the RFC ----
def chacha20_block(key: bytes, counter: int, nonce: bytes) -> bytes:
    def rotl(v, n):
        return ((v << n) | (v >> (32 - n))) & 0xFFFFFFFF

    def qr(s, a, b, c, d):
        s[a] = (s[a] + s[b]) & 0xFFFFFFFF; s[d] = rotl(s[d] ^ s[a], 16)
        s[c] = (s[c] + s[d]) & 0xFFFFFFFF; s[b] = rotl(s[b] ^ s[c], 12)
        s[a] = (s[a] + s[b]) & 0xFFFFFFFF; s[d] = rotl(s[d] ^ s[a], 8)
        s[c] = (s[c] + s[d]) & 0xFFFFFFFF; s[b] = rotl(s[b] ^ s[c], 7)

    st = [0x61707865, 0x3320646e, 0x79622d32, 0x6b206574]
    st += [int.from_bytes(key[4 * i:4 * i + 4], "little") for i in range(8)]
    st += [counter] + [int.from_bytes(nonce[4 * i:4 * i + 4], "little") for i in range(3)]
    w = st[:]
    for _ in range(10):
        qr(w, 0, 4, 8, 12); qr(w, 1, 5, 9, 13); qr(w, 2, 6, 10, 14); qr(w, 3, 7, 11, 15)
        qr(w, 0, 5, 10, 15); qr(w, 1, 6, 11, 12); qr(w, 2, 7, 8, 13); qr(w, 3, 4, 9, 14)
    return b"".join(((w[i] + st[i]) & 0xFFFFFFFF).to_bytes(4, "little") for i in range(16))


def chacha20_encrypt(key, counter, nonce, pt):
    out = bytearray()
    for j in range(0, len(pt), 64):
        ks = chacha20_block(key, counter + j // 64, nonce)
        out += bytes(a ^ b for a, b in zip(pt[j:j + 64], ks))
    return bytes(out)


def pad16(b):
    return bytes((-len(b)) % 16)


def aead_mac_data(aad, ct):
    return aad + pad16(aad) + ct + pad16(ct) + len(aad).to_bytes(8, "little") + len(ct).to_bytes(8, "little")


def aead_encrypt(key, nonce, aad, pt):
    """returns (Poly1305 one-time key, ciphertext, MAC input, tag)"""
    otk = chacha20_block(key, 0, nonce)[:32]
    ct = chacha20_encrypt(key, 1, nonce, pt)
    mac = aead_mac_data(aad, ct)
    return otk, ct, mac, poly1305_ref(otk, mac)


AEAD_KEY = bytes(range(0x80, 0xA0))
AEAD_NONCE = bytes.fromhex("070000004041424344454647")
AEAD_AAD = bytes.fromhex("50515253c0c1c2c3c4c5c6c7")
AEAD_PT = (b"Ladies and Gentlemen of the class of '99: If I could offer you only one tip "
           b"for the future, sunscreen would be it.")
aead_otk, aead_ct, aead_mac, aead_tag = aead_encrypt(AEAD_KEY, AEAD_NONCE, AEAD_AAD, AEAD_PT)
assert aead_otk.hex() == "7bac2b252db447af09b67a55a4e955840ae1d6731075d9eb2a9375783ed553ff", "RFC 2.8.2 Poly1305 key"
assert aead_ct[:16].hex() == "d31a8d34648e60db7b86afbc53ef7ec2", "RFC 2.8.2 ciphertext"
assert aead_tag.hex() == "1ae10b594f09e26a7e902ecbd0600691", "RFC 2.8.2 tag"
print("ChaCha20-Poly1305 reference matches the RFC 8439 2.8.2 example (key, ciphertext, tag)")

long_vecs = [v for v in vectors if len(v[2]) > 64]                  # RFC A.3 #2, #3, #4
long_vecs.append(("RFC 2.8.2 AEAD MAC", aead_otk, aead_mac, aead_tag))
assert all(len(m) <= 512 for (_, _, m, _) in long_vecs)


# ---- write the VHDL package for the hardware testbench (messages <= 64 bytes) ----
def slv(b, nbytes):
    """bytes -> VHDL hex literal, byte 0 in bits 7..0 (zero padded to nbytes)"""
    return 'x"' + f"{int.from_bytes(b, 'little'):0{2 * nbytes}x}" + '"'


hw_vecs = [(n, k, m, t) for (n, k, m, t) in vectors if len(m) <= 64]
hw_vecs += [(f"length {n}", sweep_key, sweep_msg[:n], sweep_tags[n]) for n in range(65)]
VHD = ROOT / "hw" / "tb_poly1305_vectors_pkg.vhd"
with VHD.open("w", newline="\n") as f:
    f.write("-- tb_poly1305_vectors_pkg.vhd - generated by scripts/gen_poly1305_vectors.py, do not edit.\n"
            "-- Poly1305 test vectors for the hardware testbench (messages up to 64 bytes):\n"
            "-- official RFC 8439 vectors + every length 0..64 (independent big-integer reference).\n"
            "-- Byte order: byte 0 is in bits 7..0.\n")
    f.write("library ieee;\nuse ieee.std_logic_1164.all;\n\npackage tb_poly1305_vectors is\n\n")
    f.write("    type poly_tv_t is record\n"
            "        name : string(1 to 20);\n"
            "        key  : std_logic_vector(255 downto 0);\n"
            "        len  : natural;\n"
            "        msg  : std_logic_vector(511 downto 0);\n"
            "        tag  : std_logic_vector(127 downto 0);\n"
            "    end record;\n"
            "    type poly_tv_array_t is array (natural range <>) of poly_tv_t;\n\n")
    f.write(f"    constant POLY_NUM_RFC : natural := {len(hw_vecs) - 65};   -- the first entries are RFC vectors\n")
    f.write("    constant POLY_TVS : poly_tv_array_t := (\n")
    rows = []
    for name, key, msg, tag in hw_vecs:
        rows.append(f'        ("{name[:20]:<20}",\n'
                    f'         {slv(key, 32)},\n'
                    f'         {len(msg)},\n'
                    f'         {slv(msg, 64)},\n'
                    f'         {slv(tag, 16)})')
    f.write(",\n".join(rows))
    f.write("\n    );\n\n")
    # long messages: sent in pieces (init / final control bits)
    f.write("    -- long messages (more than 64 bytes): the testbench sends them in pieces\n")
    f.write("    type poly_long_tv_t is record\n"
            "        name : string(1 to 20);\n"
            "        key  : std_logic_vector(255 downto 0);\n"
            "        len  : natural;\n"
            "        msg  : std_logic_vector(4095 downto 0);\n"
            "        tag  : std_logic_vector(127 downto 0);\n"
            "    end record;\n"
            "    type poly_long_tv_array_t is array (natural range <>) of poly_long_tv_t;\n\n")
    f.write("    constant POLY_LONG_TVS : poly_long_tv_array_t := (\n")
    rows = []
    for name, key, msg, tag in long_vecs:
        rows.append(f'        ("{name[:20]:<20}",\n'
                    f'         {slv(key, 32)},\n'
                    f'         {len(msg)},\n'
                    f'         {slv(msg, 512)},\n'
                    f'         {slv(tag, 16)})')
    f.write(",\n".join(rows))
    f.write("\n    );\n\nend package;\n")
print(f"wrote {VHD.relative_to(ROOT)}  ({len(hw_vecs)} vectors + {len(long_vecs)} long)")
